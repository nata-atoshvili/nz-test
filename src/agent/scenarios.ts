import type { Message } from '@/types/chat';

const topics = {
    newton: {
        normal: 'Второй закон Ньютона объясняет, как сила меняет движение тела.\n\nФормула: F = m × a, где F — сила, m — масса, a — ускорение.\n\nПредставь тележку в магазине: чем сильнее ты её толкаешь, тем быстрее она разгоняется. Но загруженную тележку разогнать труднее — у неё больше масса.\n\nКак думаешь, что произойдёт с ускорением, если при той же массе увеличить силу вдвое?',
        simple: 'Представь пустую тележку. Слегка толкнёшь — она медленно разгонится. Толкнёшь сильнее — разгонится быстрее.\n\nА теперь положи в неё тяжёлый рюкзак. Чтобы разогнать её так же быстро, придётся толкать сильнее.\n\nЭто и есть второй закон Ньютона: больше сила — больше ускорение; больше масса — труднее разогнать.'
    },
    ohm: {
        normal: 'Закон Ома связывает напряжение, силу тока и сопротивление: I = U / R.\n\nПредставь воду в трубе: напряжение похоже на напор, ток — на поток воды, а сопротивление — на узкий участок трубы.\n\nПри напряжении 12 В и сопротивлении 6 Ом сила тока равна 2 А.\n\nА какой будет ток, если сопротивление увеличить вдвое, оставив напряжение прежним?',
        simple: 'Представь воду в шланге. Сильнее напор — больше воды протекает. Сожмёшь шланг — воде станет труднее течь.\n\nС электричеством похоже: напряжение «толкает» ток, а сопротивление ему мешает. Это и описывает закон Ома.'
    },
    fractions: {
        normal: 'Дробь — это часть целого. Например, 1/4 пиццы — один из четырёх равных кусочков.\n\nЧтобы сложить 1/2 и 1/4, сначала выразим их одинаковыми долями: 1/2 = 2/4. Теперь 2/4 + 1/4 = 3/4.\n\nЗнаменатель показывает размер долей, числитель — сколько их взяли.\n\nПопробуешь по тому же принципу сложить 1/3 и 1/6?',
        simple: 'Разрежь пиццу на четыре одинаковых кусочка. Один кусочек — это 1/4, два — 2/4, то есть половина.\n\nЕсли взять половину пиццы и ещё один кусочек, получится три кусочка из четырёх: 3/4.'
    }
};
function topicOf(text: string): keyof typeof topics | undefined {
    if (/ньютон|ускорени|тележк/i.test(text)) return 'newton';
    if (/закон.*ома|сопротивлен|напряжени|электрич/i.test(text)) return 'ohm';
    if (/дроб|пицц/i.test(text)) return 'fractions';
}
export function makeAnswer(history: Message[]): { text: string; toolResult?: string } {
    const users = history.filter((m) => m.role === 'user');
    const prompt = users.at(-1)?.text ?? '';
    const expression = prompt.match(/(-?\d+(?:[.,]\d+)?)\s*([×*÷/+:−-])\s*(-?\d+(?:[.,]\d+)?)/);
    if (expression) {
        const a = Number(expression[1].replace(',', '.'));
        const b = Number(expression[3].replace(',', '.'));
        const op = expression[2];
        if (['/', '÷', ':'].includes(op) && b === 0)
            return {
                text: 'На ноль делить нельзя: результат такого деления не определён. Попробуй изменить делитель — разберём пример вместе.'
            };
        const result = ['*', '×'].includes(op)
            ? a * b
            : ['/', '÷', ':'].includes(op)
              ? a / b
              : op === '+'
                ? a + b
                : a - b;
        if (!Number.isFinite(result))
            return {
                text: 'Числа в этом примере слишком большие для моего учебного калькулятора. Попробуй пример с меньшими числами.'
            };
        const formatted = Number(result.toPrecision(12)).toLocaleString('ru-RU');
        const toolResult = `${expression[1]} ${op} ${expression[3]} = ${formatted}`;
        if (/не (?:давай|говори|показывай).*ответ|подсказ/i.test(prompt))
            return {
                text: `Давай решим по шагам, без готового ответа.\n\n${['*', '×'].includes(op) ? `Разложи ${b} на удобные слагаемые и умножь ${a} на каждое из них. Затем сложи результаты.` : 'Начни с небольших удобных чисел и вспомни правило этой операции.'}\n\nКакой первый шаг у тебя получается?`,
                toolResult: 'Вычисление проверено. Ответ скрыт по твоей просьбе.'
            };
        return {
            text: `Получается ${toolResult}.\n\n${a === 17 && b === 24 && ['*', '×'].includes(op) ? 'Можно проверить в уме: 17 × 20 = 340, а 17 × 4 = 68. Складываем: 340 + 68 = 408.' : 'Калькулятор помог проверить результат. Если хочешь, пришли пример с просьбой «не давай ответ сразу» — начнём с подсказки.'}`,
            toolResult
        };
    }
    const topic =
        topicOf(prompt) ??
        [...users.slice(0, -1)]
            .reverse()
            .map((m) => topicOf(m.text))
            .find(Boolean);
    if (/проще|простыми|не понял|не поняла/i.test(prompt) && topic) return { text: topics[topic].simple };
    if (topicOf(prompt)) return { text: topics[topicOf(prompt)!].normal };
    if (/пример|ещ[её]/i.test(prompt) && topic)
        return {
            text: `Вернёмся к нашей теме.\n\n${topics[topic].simple}\n\nПопробуй придумать похожий пример из своей жизни — я помогу его разобрать.`
        };
    if (/ошибк|сбой/i.test(prompt))
        return {
            text: 'Теперь всё получилось! Это был учебный сценарий сбоя. Повторная попытка завершилась успешно, а история диалога сохранилась.\n\nМожем продолжить: спроси о законе Ома, втором законе Ньютона, дробях или пришли арифметический пример.'
        };
    return {
        text: 'Давай разберёмся вместе. Сейчас я работаю в деморежиме и умею объяснять закон Ома, второй закон Ньютона и дроби, а ещё проверять простые арифметические примеры.\n\nНапиши, например, «Объясни второй закон Ньютона». После ответа можно попросить «Объясни проще» — я учту тему нашего разговора.'
    };
}
